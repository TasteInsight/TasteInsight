import commonMappings from '@unicode/unicode-17.0.0/Case_Folding/C/symbols.mjs';
import fullMappings from '@unicode/unicode-17.0.0/Case_Folding/F/symbols.mjs';
import { readFile, writeFile } from 'node:fs/promises';
import { format, resolveConfig } from 'prettier';
import { fileURLToPath } from 'node:url';

const root = new URL('../../', import.meta.url);
const check = process.argv.includes('--check');
const mappings = Object.fromEntries(
  [...commonMappings, ...fullMappings].map(([character, folded]) => [
    character.codePointAt(0),
    folded,
  ]),
);
const data = JSON.stringify(mappings).replace(
  /[\u007f-\uffff]/g,
  (character) => '\\u' + character.charCodeAt(0).toString(16).padStart(4, '0'),
);
const source = `// Generated by backend/scripts/generate-allergen-case-fold.mjs.
// Unicode 17.0.0 Default Full Case Folding: https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt
// Data source: @unicode/unicode-17.0.0@2.0.8 (MIT).
const mappings: Readonly<Record<number, string>> = JSON.parse(${JSON.stringify(data)});

export function unicodeCaseFold(value: string): string {
  return Array.from(value, (character) => mappings[character.codePointAt(0)!] ?? character).join('');
}
`;

const outputs = [
  'backend/src/allergens/unicode-case-fold.ts',
  'frontend-miniapp/src/utils/unicode-case-fold.ts',
  'frontend-web/src/utils/unicode-case-fold.ts',
].map((path) => [path, source]);

const migrationPath =
  'backend/prisma/migrations/20261023000100_allergen_normalization/migration.sql';
const previous = await readFile(new URL(migrationPath, root), 'utf8');
const sql = `CREATE FUNCTION allergen_comparison_key(value TEXT) RETURNS TEXT
LANGUAGE SQL IMMUTABLE STRICT PARALLEL SAFE AS $$
  -- Unicode 17.0.0 Default Full Case Folding, generated from @unicode/unicode-17.0.0@2.0.8 (MIT).
  SELECT COALESCE(string_agg(COALESCE(mappings ->> ascii(character)::TEXT, character), '' ORDER BY ordinal), '')
  FROM regexp_split_to_table(normalize_allergen_text(value), '') WITH ORDINALITY AS chars(character, ordinal)
  CROSS JOIN (SELECT '${data}'::JSONB AS mappings) AS data;
$$;`;
const current = previous.match(
  /CREATE FUNCTION allergen_comparison_key\(value TEXT\)[\s\S]*?\$\$;/,
)?.[0];
if (!current)
  throw new Error('Missing allergen comparison function: ' + migrationPath);
outputs.push([migrationPath, previous.replace(current, () => sql)]);

for (const [path, raw] of outputs) {
  const target = new URL(path, root);
  const expected = path.endsWith('.ts')
    ? await format(raw, {
        ...(await resolveConfig(fileURLToPath(target))),
        parser: 'typescript',
      })
    : raw;
  if (check) {
    if ((await readFile(target, 'utf8')) !== expected)
      throw new Error('Generated case folding is out of date: ' + path);
  } else {
    await writeFile(target, expected);
  }
}
console.log(
  `${check ? 'Verified' : 'Generated'} Unicode 17 case folding for ${outputs.length} outputs.`,
);
